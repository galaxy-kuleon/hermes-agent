"""The image must use its build-time TUI, never a runtime npm repair."""

from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]


def test_dockerfile_uses_prebuilt_tui_instead_of_writable_node_modules() -> None:
    dockerfile = (REPO_ROOT / "Dockerfile").read_text(encoding="utf-8")
    setup = (REPO_ROOT / "setup-hermes.sh").read_text(encoding="utf-8")

    assert "ENV HERMES_TUI_DIR=/opt/hermes/ui-tui" in dockerfile
    assert "(cd ui-tui && npm run build" in setup
    assert "test -f /opt/hermes/ui-tui/dist/entry.js" in dockerfile
    assert "chown -R hermes:hermes /opt/hermes/ui-tui" not in dockerfile
    assert "chown -R hermes:hermes /opt/hermes/node_modules" not in dockerfile
